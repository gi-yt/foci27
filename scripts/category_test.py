#!/usr/bin/env python3

"""
Does OONI/Poisoned Wells disagreement depend on the website category?
For domain x ISP combos with a 0/1 Poisoned Wells value, a chi-square test
of independence between PW category and agree (agree_blocked / agree_ok)
vs disagree (mixed or contradiction). Categories with fewer than
--min-combos combos are pooled as "other". Run for both years, with all
measurements and with ISP-resolver measurements only.

Output: category_test.txt
"""

import argparse
import math
from collections import Counter, defaultdict

from common import load_dnsblocks, read_csv
from paths import (
    CATEGORY_TEST_TXT,

    RESOLVER_SPLIT_CSV,
    RESOLVER_SPLIT_CSV_2026,
    RESULTS_2025,
    RESULTS_2026,
)

AGREE = {"agree_blocked", "agree_ok"}

def gammaincc(a, x):
    """
    Regularized upper incomplete gamma Q(a, x) (series for small x,
    Lentz continued fraction otherwise).
    """

    if x <= 0:
        return 1.0
    log_front = -x + a * math.log(x) - math.lgamma(a)
    if x < a + 1:
        term = total = 1.0 / a
        ap = a
        for _ in range(10000):
            ap += 1
            term *= x / ap
            total += term
            if abs(term) < abs(total) * 1e-15:
                break
        return max(0.0, 1.0 - total * math.exp(log_front))
    tiny = 1e-300
    b = x + 1 - a
    c = 1 / tiny
    d = 1 / b
    h = d
    for i in range(1, 10000):
        an = -i * (i - a)
        b += 2
        d = an * d + b
        d = tiny if abs(d) < tiny else d
        c = b + an / c
        c = tiny if abs(c) < tiny else c
        d = 1 / d
        delta = d * c
        h *= delta
        if abs(delta - 1) < 1e-15:
            break
    return math.exp(log_front) * h

def chi_square(table):
    """
    (statistic, degrees of freedom, p-value, smallest expected count,
    cells with expected count < 5) for {row: [col0, col1]}.
    """

    rows = list(table.values())
    n = sum(sum(r) for r in rows)
    col = [sum(r[j] for r in rows) for j in range(2)]
    stat, expected = 0.0, []
    for r in rows:
        total = sum(r)
        for j in range(2):
            e = total * col[j] / n
            expected.append(e)
            stat += (r[j] - e) ** 2 / e
    df = len(rows) - 1
    return stat, df, gammaincc(df / 2, stat / 2), min(expected), sum(e < 5 for e in expected), n

def run(name, rows, category, min_combos):
    rows = [r for r in rows if r["pw_status"] in ("blocked", "not_blocked")]
    counts = Counter(category(r) for r in rows)
    table = defaultdict(lambda: [0, 0])
    for r in rows:
        cat = category(r)
        cat = cat if counts[cat] >= min_combos else "other"
        table[cat][0 if r["agreement"] in AGREE else 1] += 1

    stat, df, p, min_e, small, n = chi_square(table)
    v = math.sqrt(stat / n)
    order = sorted(table, key=lambda c: (c == "other", -sum(table[c])))
    return [
        f"{name}: {n} combos, {len(table)} categories (fewer than {min_combos} combos pooled as other)",
        "  disagreement rate: " + ", ".join(
            f"{c} {100 * table[c][1] / sum(table[c]):.0f}% of {sum(table[c])}" for c in order
        ),
        f"  chi-square {stat:.1f}, df {df}, p = {p:.2g}, Cramer's V {v:.2f}; smallest expected count "
        f"{min_e:.1f} ({small} {'cell' if small == 1 else 'cells'} below 5)",
        f"  -> {'category and disagreement are associated' if p < 0.05 else 'no significant association'} "
        f"at the 5% level; V {'< 0.1 negligible' if v < 0.1 else '< 0.3 weak' if v < 0.3 else '< 0.5 moderate' if v < 0.5 else '>= 0.5 strong'}",
    ]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--min-combos", type=int, default=20)
    parser.add_argument("--txt", default=str(CATEGORY_TEST_TXT))
    args = parser.parse_args()

    categories = {r["domain"]: r["pw_category"] for r in load_dnsblocks()}
    category = lambda r: categories.get(r["domain"], "not_in_blocklist")

    def usable(path):
        return [r for r in read_csv(path) if int(r["n_usable"]) > 0]

    def isp_only(path):
        return [r for r in read_csv(path) if r["resolver_class"] == "isp"]

    out = [
        "Does disagreement with Poisoned Wells depend on website category? (chi-square test)",
        "Generated by scripts/category_test.py",
        "",
        "Agree = agree_blocked or agree_ok; disagree = mixed or contradiction; combos with a 0/1 PW value",
        "",
    ]
    for name, rows in [
        ("2025, all resolvers", usable(RESULTS_2025 / "domain_isp.csv")),
        ("2025, ISP resolver", isp_only(RESOLVER_SPLIT_CSV)),
        ("2026, all resolvers", usable(RESULTS_2026 / "domain_isp.csv")),
        ("2026, ISP resolver", isp_only(RESOLVER_SPLIT_CSV_2026)),
    ]:
        out += run(name, rows, category, args.min_combos) + [""]

    out.append(
        "Caveat: combos of the same domain on different ISPs are not independent, so p-values are "
        "optimistic; categories are PW's (best-effort, per the report)"
    )
    out.append("")

    with open(args.txt, "w") as f:
        f.write("\n".join(out))
    print("\n".join(out))

if __name__ == "__main__":
    main()
