#!/usr/bin/env python3

"""
How much do the agreement results depend on the verdict cutoffs?
Recomputes the domain x ISP agreement with several (ok_max, blocked_min)
pairs, for both years, with all measurements and with ISP-resolver
measurements only. The default everywhere else is 0.1 / 0.9.

Output: robustness.txt
"""

import argparse
from collections import Counter

from common import (
    AGREEMENT_LABELS,
    add_agreement,
    add_verdicts,
    aggregate,
    apply_window,
    load_ooni,
    pw_lookup,
)
from paths import OONI_2025, OONI_2026, REPORT_META_2026, ROBUSTNESS_TXT
from resolver_split import label_resolvers, load_resolver_raw

CUTOFFS = [(0.05, 0.95), (0.1, 0.9), (0.2, 0.8), (0.3, 0.7)]


def agreement_rows(rows, pw, ok_max, blocked_min):
    out = []
    for key, r in aggregate(rows, ["domain", "isp"]).items():
        meta = pw.get(key)
        r["pw_status"] = meta["pw_status"] if meta else "not_in_blocklist"
        add_agreement(add_verdicts(r, ok_max=ok_max, blocked_min=blocked_min))
        if r["n_usable"] > 0:
            out.append(r)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--txt", default=str(ROBUSTNESS_TXT))
    args = parser.parse_args()

    pw = pw_lookup()
    o25, _, _ = label_resolvers(apply_window(load_ooni(OONI_2025), 7), load_resolver_raw())
    o26, _, _ = label_resolvers(load_ooni(OONI_2026), load_resolver_raw([REPORT_META_2026]))

    datasets = [
        ("2025, all resolvers", o25),
        ("2025, ISP resolver", [r for r in o25 if r["resolver_class"] == "isp"]),
        ("2026, all resolvers", o26),
        ("2026, ISP resolver", [r for r in o26 if r["resolver_class"] == "isp"]),
    ]

    out = [
        "Agreement with Poisoned Wells under different OONI verdict cutoffs",
        "Generated by scripts/robustness.py",
        "",
        "Cutoffs: ok if blocked share <= first value, blocked if >= second value, mixed in between "
        "(default 0.1 / 0.9)",
    ]
    summary = {}
    for name, rows in datasets:
        out += ["", f"{name}:"]
        for ok_max, blocked_min in CUTOFFS:
            r = agreement_rows(rows, pw, ok_max, blocked_min)
            c = Counter(x["agreement"] for x in r)
            mixed = sum(1 for x in r if x["ooni_verdict"] == "mixed")
            clean = c["ooni_only_blocked"] + c["pw_only_blocked"]
            mixed01 = c["pw_blocked/ooni_mixed"] + c["pw_ok/ooni_mixed"]
            summary[(name, ok_max)] = (c["agree_blocked"], mixed, len(r), clean, mixed01)
            out.append(
                f"  {ok_max:.2f} / {blocked_min:.2f}  {len(r):>4} combos: "
                + ", ".join(f"{label} {c.get(label, 0)}" for label in AGREEMENT_LABELS)
                + f" | mixed {mixed} ({100 * mixed / len(r):.0f}%)"
            )

    # Do the main conclusions hold at every cutoff?
    def holds(pred):
        return all(pred(ok) for ok, _ in CUTOFFS)

    def mixed_pct(name, ok):
        _, mixed, n, _, _ = summary[(name, ok)]
        return 100 * mixed / n

    out += [
        "",
        "Conclusions checked at every cutoff:",
        "  ISP-resolver measurements give fewer mixed verdicts than all measurements (both years): "
        + ("holds" if holds(lambda ok: mixed_pct("2025, ISP resolver", ok) < mixed_pct("2025, all resolvers", ok)
                            and mixed_pct("2026, ISP resolver", ok) < mixed_pct("2026, all resolvers", ok)) else "DOES NOT hold"),
        "  ISP-resolver measurements give more agree-blocked combos than all measurements (both years): "
        + ("holds" if holds(lambda ok: summary[("2025, ISP resolver", ok)][0] > summary[("2025, all resolvers", ok)][0]
                            and summary[("2026, ISP resolver", ok)][0] > summary[("2026, all resolvers", ok)][0]) else "DOES NOT hold"),
        "  Among disagreements with a 0/1 PW value, mixed outnumber clean contradictions "
        "(2025, all resolvers): " + ", ".join(
            f"{ok:.2f}/{bm:.2f} {summary[('2025, all resolvers', ok)][4]} vs {summary[('2025, all resolvers', ok)][3]}"
            f" ({'yes' if summary[('2025, all resolvers', ok)][4] > summary[('2025, all resolvers', ok)][3] else 'no'})"
            for ok, bm in CUTOFFS
        ) + ", so this depends on the cutoffs",
        "  Range of agree-blocked combos, 2025 ISP resolver: "
        + f"{min(summary[('2025, ISP resolver', ok)][0] for ok, _ in CUTOFFS)}"
        + f"-{max(summary[('2025, ISP resolver', ok)][0] for ok, _ in CUTOFFS)}",
        "",
    ]

    with open(args.txt, "w") as f:
        f.write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
